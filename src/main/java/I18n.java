    /**
     * The requested launcher languages are localized in the translation table.
     * Older extra languages are partial and still show the incomplete warning.
     */
    static boolean isTranslationComplete(AppLanguage language) {
        return language == AppLanguage.EN
                || language == AppLanguage.RU
                || language == AppLanguage.FR
                || language == AppLanguage.IT
                || language == AppLanguage.JA
                || language == AppLanguage.RO
                || language == AppLanguage.ZH;
    }

    static String t(AppLanguage language, String key) {
        Map<String, String> map = TRANSLATIONS.getOrDefault(language, EN);
        return map.getOrDefault(key, EN.getOrDefault(key, key));
    }

    static String format(AppLanguage language, String key, Object... args) {
        return MessageFormat.format(t(language, key), args);
    }

    private static Map<String, String> map(String... pairs) {
        HashMap<String, String> map = new HashMap<>();
        for (int i = 0; i + 1 < pairs.length; i += 2) {
            map.put(pairs[i], pairs[i + 1]);
        }
        return map;
    }

